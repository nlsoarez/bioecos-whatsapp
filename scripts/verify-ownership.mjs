// Run only against a disposable PostgreSQL database after migrate and seed.
import assert from 'node:assert/strict';
import pg from 'pg';
import { createServer } from 'node:http';
import { PostgresRepository } from '../dist/src/repositories/postgres.repository.js';
import { ConversationService } from '../dist/src/services/conversation.service.js';
import { CoordinatorNotificationService } from '../dist/src/services/coordinator-notification.service.js';
import { EvolutionService } from '../dist/src/services/evolution.service.js';
import { loadEnv } from '../dist/src/config/env.js';
assert.match(process.env.DATABASE_URL ?? '', /ownership-test/);
const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL });
const repo = new PostgresRepository(pool, 'ownership-test-cipher');
let fail = false, missingId = false;
const sent = [];
const server = createServer(async (req, res) => {
  let body = ''; for await (const chunk of req) body += chunk;
  if (fail) { res.writeHead(503); res.end('{}'); return; }
  sent.push(JSON.parse(body));
  res.setHeader('content-type', 'application/json');
  res.end(JSON.stringify(missingId ? {} : {key: {id: `simulated-${sent.length}`}}));
});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const sender = new EvolutionService(loadEnv({...process.env, EVOLUTION_API_URL: `http://127.0.0.1:${server.address().port}`, EVOLUTION_API_KEY: 'test', EVOLUTION_MAX_RETRIES: '0'}));
const notifier = new CoordinatorNotificationService(repo, sender, async () => '5521999994321', 'https://example.test');
const agent = { embed: async () => null, respond: async () => 'Resposta normal' };
const message = (text, id) => ({content: text, externalMessageId: id, phone: '5521988881234', pushName: 'Teste isolado', timestamp: new Date(), raw: {}});
const service = new ConversationService(repo, agent, sender, notifier);
try {
  await service.handle(message('oi', 'start'));
  const {context: initial} = await repo.ingestInbound(message('context', 'context'));
  let release;
  const waiting = new Promise(resolve => {release = resolve;});
  let entered;
  const started = new Promise(resolve => {entered = resolve;});
  const sending = repo.sendAuthorized(initial, 'serialized', async () => {entered(); await waiting; return sender.sendText(initial.phone, 'serialized');});
  await started;
  let transferred = false;
  const transition = repo.setConversationWorkflow(initial.conversationId, 'coordinator_attending', 'coordinator', 'Test').then(() => {transferred = true;});
  await new Promise(resolve => setTimeout(resolve, 100));
  assert.equal(transferred, false, 'transfer must wait for authorized send');
  release(); await sending; await transition;
  assert.equal(await repo.sendAuthorized(initial, 'stale', () => {throw new Error('must not send');}), false);
  await repo.setConversationWorkflow(initial.conversationId, 'ai_attending', 'ai', 'Returned', 'dashboard:test-operator');
  assert.equal(await repo.sendAuthorized(initial, 'stale-after-return', () => {throw new Error('must not send');}), false);
  assert.equal((await service.handle({...message('oi', 'queued'), timestamp: new Date(0)})).status, 'paused');
  await new Promise(resolve => setTimeout(resolve, 5));
  await service.handle(message('quero atendimento humano', 'handoff'));
  const count = sent.length;
  for (const [index, text] of ['oi', 'SAIR', 'imagem'].entries()) assert.equal((await service.handle(message(text, `paused-${index}`))).status, 'paused');
  assert.equal(sent.length, count);
  const notifications = await repo.listCoordinatorNotifications('', 50);
  assert.equal(notifications.length, 1);
  assert.equal(notifications[0].status, 'accepted');
  assert.equal((await service.handle(message('quero atendimento humano', 'handoff'))).status, 'duplicate');
  await notifier.retry(notifications[0].id);
  assert.equal(sent.length, count);
  const restored = new PostgresRepository(pool, 'ownership-test-cipher');
  assert.equal((await restored.getContext(initial.conversationId)).currentOwner, 'coordinator');
  await restored.recordHumanOutbound({ ...message('serialized', 'unused'), externalMessageId: 'simulated-2' });
  assert.equal((await restored.getContext(initial.conversationId)).workflowState, 'awaiting_coordinator', 'late automated receipt must not change owner');
  await assert.rejects(repo.setAutomationPaused(initial.conversationId, false, 'admin'));
  await assert.rejects(repo.setConversationWorkflow(initial.conversationId, 'ai_attending', 'ai', 'unauthorized'));
  await repo.setConversationWorkflow(initial.conversationId, 'ai_attending', 'ai', 'Returned', 'dashboard:test-operator');
  await new Promise(resolve => setTimeout(resolve, 5));
  fail = true;
  await service.handle(message('quero atendimento humano', 'failure')).catch(() => {});
  assert.equal((await repo.getContext(initial.conversationId)).currentOwner, 'coordinator');
  const pending = (await repo.listCoordinatorNotifications('pending', 50))[0];
  assert.ok(pending);
  fail = false;
  await pool.query('UPDATE coordinator_notifications SET next_attempt_at = now() WHERE id = $1', [pending.id]);
  await Promise.all([notifier.runDue(), new CoordinatorNotificationService(repo, sender, async () => '5521999994321', '').runDue()]);
  assert.equal((await repo.getCoordinatorNotification(pending.id)).status, 'accepted');
  missingId = true;
  await assert.rejects(sender.sendText(initial.phone, 'missing-id'));
  const audit = await pool.query("SELECT actor FROM audit_logs WHERE action = 'conversation.returned_to_automation'");
  assert.ok(audit.rows.every(row => row.actor === 'dashboard:test-operator'));
  console.log('PASS: PostgreSQL serialization, stale output, human silence, queued events, restart, return audit, idempotency, retry concurrency, missing provider ID');
} finally { server.close(); await pool.end(); }
